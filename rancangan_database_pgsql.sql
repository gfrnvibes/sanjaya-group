-- =====================================================================
-- RANCANGAN DATABASE – Sistem Konveksi + Reseller (Laravel 13 + Filament 5 + PostgreSQL 16)
-- Dibuat 16 Okt 2026 dari alur 2 file Excel aktif (Produksi & Stok v2 + Penjualan Reseller v2)
--
-- PRINSIP
--  * 3NF: setiap fakta disimpan sekali. Pemilik/reseller/channel sebuah penjualan
--    TIDAK disalin ke baris penjualan – diturunkan dari stores -> resellers -> owners.
--  * Pengecualian yang disengaja = SNAPSHOT historis di baris transaksi
--    (harga reseller, % tier, HPP, fee channel) supaya laporan lama tidak berubah
--    ketika harga/HPP/tier naik. Ini sama dengan "BERLAKU MULAI" di Excel.
--  * Harga, HPP, tier, fee channel = tabel RIWAYAT dengan effective_from.
--  * Stok = LEDGER (stock_movements / material_movements). Saldo cepat di
--    *_balances yang diperbarui TRIGGER dalam transaksi yang sama.
--  * Transaksi tidak dihapus: pakai status + baris pembalik. Soft delete hanya master.
--  * Uang numeric(15,2); persen numeric(7,4) (0.2000 = 20%); qty barang integer;
--    qty bahan numeric(14,3). Enum = varchar + CHECK (cast ke PHP Enum di model).
--  * Nama tabel/kolom mengikuti konvensi Laravel (plural snake_case, *_id, timestamps).
-- =====================================================================

-- ---------------------------------------------------------------------
-- 0. AKSES & PENGATURAN
-- ---------------------------------------------------------------------
CREATE TABLE owners (                      -- PEMILIK
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          varchar(30)  NOT NULL UNIQUE,
    name          varchar(120) NOT NULL,
    phone         varchar(30),
    is_active     boolean NOT NULL DEFAULT true,
    created_at    timestamptz, updated_at timestamptz, deleted_at timestamptz
);

CREATE TABLE users (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              varchar(120) NOT NULL,
    email             varchar(190) NOT NULL UNIQUE,
    password          varchar(255) NOT NULL,
    owner_id          bigint REFERENCES owners(id),   -- NULL = staf konveksi; terisi = user panel reseller
    is_active         boolean NOT NULL DEFAULT true,
    remember_token    varchar(100),
    email_verified_at timestamptz,
    created_at timestamptz, updated_at timestamptz
);
-- roles/permissions: tabel bawaan spatie/laravel-permission (roles, permissions, model_has_roles, ...)
-- audit: tabel bawaan spatie/laravel-activitylog (activity_log)

CREATE TABLE settings (                    -- pengganti sheet PENGATURAN
    key        varchar(80) PRIMARY KEY,    -- margin_default, price_rounding, price_tolerance_pct,
    value      jsonb NOT NULL,             -- analysis_days, target_stock_days, lead_time_days, ...
    updated_at timestamptz
);

-- ---------------------------------------------------------------------
-- 1. RESELLER, TOKO, CHANNEL, TIER
-- ---------------------------------------------------------------------
CREATE TABLE resellers (                   -- RESELLER / brand
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id             bigint NOT NULL REFERENCES owners(id),
    name                 varchar(120) NOT NULL UNIQUE,
    opening_balance      numeric(15,2) NOT NULL DEFAULT 0,   -- saldo tagihan awal (Juni)
    opening_balance_date date,
    is_active            boolean NOT NULL DEFAULT true,
    created_at timestamptz, updated_at timestamptz, deleted_at timestamptz
);
CREATE INDEX resellers_owner_idx ON resellers(owner_id);

CREATE TABLE channels (                    -- MASTER CHANNEL
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code      varchar(20) NOT NULL UNIQUE,  -- SHOPEE, TIKTOK, LAZADA, BLIBLI, WEBSITE, WA, OFFLINE, LAINNYA
    name      varchar(60) NOT NULL,
    kind      varchar(15) NOT NULL CHECK (kind IN ('marketplace','website','chat','offline','other')),
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE channel_fee_rates (           -- % potongan admin & iklan (riwayat)
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id     bigint NOT NULL REFERENCES channels(id),
    effective_from date   NOT NULL,
    admin_fee_pct  numeric(7,4) NOT NULL DEFAULT 0 CHECK (admin_fee_pct BETWEEN 0 AND 1),
    ads_pct        numeric(7,4) NOT NULL DEFAULT 0 CHECK (ads_pct BETWEEN 0 AND 1),
    UNIQUE (channel_id, effective_from)
);

CREATE TABLE stores (                      -- NAMA TOKO (1 toko = 1 reseller di 1 channel)
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reseller_id  bigint NOT NULL REFERENCES resellers(id),
    channel_id   bigint NOT NULL REFERENCES channels(id),
    name         varchar(120) NOT NULL UNIQUE,      -- "ARR SANJAYA Shopee", "ARR SANJAYA WA"
    external_ref varchar(120),                      -- shop id BigSeller / marketplace
    is_active    boolean NOT NULL DEFAULT true,
    created_at timestamptz, updated_at timestamptz, deleted_at timestamptz
);
CREATE INDEX stores_reseller_idx ON stores(reseller_id);

CREATE TABLE price_tiers (                 -- TIER 1/2/3
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           varchar(20) NOT NULL UNIQUE,
    name           varchar(60) NOT NULL,
    adjustment_pct numeric(7,4) NOT NULL DEFAULT 0     -- +0.05 = harga dasar +5%
);

CREATE TABLE owner_tier_histories (        -- tier per PEMILIK + BERLAKU MULAI
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id       bigint NOT NULL REFERENCES owners(id),
    price_tier_id  bigint NOT NULL REFERENCES price_tiers(id),
    effective_from date   NOT NULL,
    note           varchar(255),
    UNIQUE (owner_id, effective_from)
);

-- ---------------------------------------------------------------------
-- 2. PRODUK (MODEL -> VARIAN/SKU)
-- ---------------------------------------------------------------------
CREATE TABLE product_categories (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(60) NOT NULL UNIQUE);
CREATE TABLE colors (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code varchar(10) NOT NULL UNIQUE, name varchar(60) NOT NULL UNIQUE);
CREATE TABLE sizes  (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code varchar(15) NOT NULL UNIQUE, sort_order smallint NOT NULL DEFAULT 0);

CREATE TABLE product_models (              -- MODEL, mis. BC1 "Baju Chef 01"
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code               varchar(30)  NOT NULL UNIQUE,
    name               varchar(150) NOT NULL,
    category_id        bigint NOT NULL REFERENCES product_categories(id),
    kind               varchar(12)  NOT NULL DEFAULT 'produksi' CHECK (kind IN ('produksi','beli_jadi','jasa')),
    default_margin_pct numeric(7,4),         -- NULL = pakai settings.margin_default
    is_active          boolean NOT NULL DEFAULT true,
    created_at timestamptz, updated_at timestamptz, deleted_at timestamptz
);

CREATE TABLE product_variants (            -- SKU VARIAN, mis. BC1HS
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_id    bigint NOT NULL REFERENCES product_models(id),
    color_id    bigint REFERENCES colors(id),
    size_id     bigint REFERENCES sizes(id),
    sku         varchar(40)  NOT NULL UNIQUE,
    name        varchar(200) NOT NULL,
    min_stock   integer NOT NULL DEFAULT 0 CHECK (min_stock >= 0),
    margin_pct  numeric(7,4),                -- NULL = ikut model / default
    is_active   boolean NOT NULL DEFAULT true,
    created_at timestamptz, updated_at timestamptz, deleted_at timestamptz,
    UNIQUE NULLS NOT DISTINCT (model_id, color_id, size_id)
);

CREATE TABLE sku_aliases (                 -- PEMETAAN SKU BigSeller/marketplace -> varian
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alias      varchar(120) NOT NULL UNIQUE,
    variant_id bigint NOT NULL REFERENCES product_variants(id),
    source     varchar(20) NOT NULL DEFAULT 'bigseller'
);

-- ---------------------------------------------------------------------
-- 3. BAHAN, RESEP (BOM), HPP, HARGA RESELLER
-- ---------------------------------------------------------------------
CREATE TABLE suppliers (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(120) NOT NULL, phone varchar(30), is_active boolean NOT NULL DEFAULT true);

CREATE TABLE material_types (              -- DRILL, LINEN, JARING, KANCING, ...
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(30) NOT NULL UNIQUE,
    name varchar(80) NOT NULL,
    kind varchar(10) NOT NULL CHECK (kind IN ('kain','aksesoris'))
);

CREATE TABLE materials (                   -- STOK BAHAN, mis. "DRILL - HITAM"
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_type_id bigint NOT NULL REFERENCES material_types(id),
    color_id         bigint REFERENCES colors(id),
    code             varchar(60) NOT NULL UNIQUE,
    base_uom         varchar(5)  NOT NULL CHECK (base_uom IN ('cm','m','pcs','gr')),
    pack_uom         varchar(10) NOT NULL DEFAULT 'roll',
    qty_per_pack     numeric(14,3) NOT NULL CHECK (qty_per_pack > 0),   -- 1 roll drill = 3000 cm
    min_stock        numeric(14,3) NOT NULL DEFAULT 0,
    is_active        boolean NOT NULL DEFAULT true,
    UNIQUE NULLS NOT DISTINCT (material_type_id, color_id)
);

CREATE TABLE material_purchases (          -- PEMBELIAN BAHAN (header)
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id   bigint REFERENCES suppliers(id),
    purchase_date date NOT NULL,
    ref_no        varchar(60),
    note          text,
    created_by    bigint REFERENCES users(id),
    created_at timestamptz, updated_at timestamptz
);
CREATE TABLE material_purchase_items (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id bigint NOT NULL REFERENCES material_purchases(id) ON DELETE CASCADE,
    material_id bigint NOT NULL REFERENCES materials(id),
    qty_pack    numeric(14,3) NOT NULL CHECK (qty_pack > 0),
    qty_base    numeric(14,3) NOT NULL CHECK (qty_base > 0),     -- isi aktual (cm/pcs)
    total_price numeric(15,2) NOT NULL CHECK (total_price >= 0),
    unit_cost   numeric(15,4) GENERATED ALWAYS AS (total_price / qty_base) STORED
);
CREATE INDEX mpi_material_idx ON material_purchase_items(material_id);

CREATE TABLE labor_types (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code varchar(20) NOT NULL UNIQUE, name varchar(60) NOT NULL); -- POTONG, JAHIT, BORDIR, OBRAS

CREATE TABLE boms (                        -- RESEP per model (+ukuran opsional), berversi
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_id       bigint NOT NULL REFERENCES product_models(id),
    size_id        bigint REFERENCES sizes(id),            -- NULL = semua ukuran
    effective_from date NOT NULL,
    note           varchar(255),
    UNIQUE NULLS NOT DISTINCT (model_id, size_id, effective_from)
);
CREATE TABLE bom_items (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bom_id           bigint NOT NULL REFERENCES boms(id) ON DELETE CASCADE,
    line_type        varchar(10) NOT NULL CHECK (line_type IN ('material','labor')),
    material_type_id bigint REFERENCES material_types(id),
    color_mode       varchar(15) CHECK (color_mode IN ('follow_variant','fixed')),   -- "IKUT PRODUK"
    material_id      bigint REFERENCES materials(id),                                 -- bila fixed
    qty_per_unit     numeric(14,4) NOT NULL DEFAULT 1 CHECK (qty_per_unit > 0),        -- cm / pcs per produk
    labor_type_id    bigint REFERENCES labor_types(id),
    labor_rate       numeric(15,2),                                                    -- ongkos per pcs
    CHECK (
      (line_type = 'material' AND material_type_id IS NOT NULL AND color_mode IS NOT NULL
         AND (color_mode = 'follow_variant' OR material_id IS NOT NULL) AND labor_type_id IS NULL)
      OR
      (line_type = 'labor' AND labor_type_id IS NOT NULL AND labor_rate IS NOT NULL AND material_type_id IS NULL)
    )
);

CREATE TABLE variant_costs (               -- HPP per varian (riwayat). Dihitung job dari BOM x harga beli terakhir
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant_id     bigint NOT NULL REFERENCES product_variants(id),
    effective_from date NOT NULL,
    material_cost  numeric(15,2) NOT NULL DEFAULT 0,
    labor_cost     numeric(15,2) NOT NULL DEFAULT 0,
    total_cost     numeric(15,2) GENERATED ALWAYS AS (material_cost + labor_cost) STORED,
    source         varchar(10) NOT NULL CHECK (source IN ('bom','legacy','manual')),   -- legacy = HPP LAMA
    UNIQUE (variant_id, effective_from)
);

CREATE TABLE reseller_price_histories (    -- HARGA RESELLER (harga dasar) + BERLAKU MULAI
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant_id      bigint NOT NULL REFERENCES product_variants(id),
    effective_from  date NOT NULL,
    base_price      numeric(15,2) NOT NULL CHECK (base_price >= 0),
    variant_cost_id bigint REFERENCES variant_costs(id),   -- HPP yang jadi dasar
    margin_pct      numeric(7,4),
    source          varchar(10) NOT NULL CHECK (source IN ('auto','manual','import')),
    approved_by     bigint REFERENCES users(id),
    note            varchar(255),
    created_at      timestamptz,
    UNIQUE (variant_id, effective_from)
);

