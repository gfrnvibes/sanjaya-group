CREATE TABLE tailors (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(120) NOT NULL, phone varchar(30), is_active boolean NOT NULL DEFAULT true);

CREATE TABLE work_orders (                 -- SPK
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          varchar(30) NOT NULL UNIQUE,
    tailor_id     bigint REFERENCES tailors(id),
    cut_date      date NOT NULL,
    finished_date date,
    status        varchar(10) NOT NULL DEFAULT 'cutting' CHECK (status IN ('cutting','sewing','done','cancelled')),
    note          text,
    created_by    bigint REFERENCES users(id),
    created_at timestamptz, updated_at timestamptz,
    CHECK (finished_date IS NULL OR finished_date >= cut_date)
);
CREATE TABLE work_order_items (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_order_id          bigint NOT NULL REFERENCES work_orders(id),
    variant_id             bigint NOT NULL REFERENCES product_variants(id),
    qty_cut                integer NOT NULL CHECK (qty_cut > 0),
    qty_good               integer NOT NULL DEFAULT 0 CHECK (qty_good >= 0),
    qty_reject             integer NOT NULL DEFAULT 0 CHECK (qty_reject >= 0),
    material_cost_snapshot numeric(15,2),      -- biaya bahan/pcs saat dipotong
    labor_cost_snapshot    numeric(15,2),      -- ongkos/pcs saat dipotong
    UNIQUE (work_order_id, variant_id),
    CHECK (qty_good + qty_reject <= qty_cut)
);
