CREATE TABLE warehouses (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code varchar(20) NOT NULL UNIQUE, name varchar(80) NOT NULL);

CREATE TABLE stock_movements (             -- SEMUA keluar-masuk barang jadi
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant_id    bigint NOT NULL REFERENCES product_variants(id),
    warehouse_id  bigint NOT NULL REFERENCES warehouses(id),
    moved_at      timestamptz NOT NULL,
    qty           integer NOT NULL CHECK (qty <> 0),      -- + masuk, - keluar
    movement_type varchar(20) NOT NULL CHECK (movement_type IN
                  ('opening','production_in','goods_in','return_in','sale_out','sale_cancel','adjustment','opname')),
    unit_cost     numeric(15,2),
    source_type   varchar(60),                            -- morph: App\Models\WorkOrderItem, SalesOrderItem, ...
    source_id     bigint,
    note          varchar(255),
    created_by    bigint REFERENCES users(id),
    created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX sm_variant_time_idx ON stock_movements(variant_id, moved_at);
CREATE INDEX sm_source_idx       ON stock_movements(source_type, source_id);
CREATE INDEX sm_type_time_idx    ON stock_movements(movement_type, moved_at);

CREATE TABLE stock_balances (              -- cache saldo (diisi trigger)
    variant_id   bigint NOT NULL REFERENCES product_variants(id),
    warehouse_id bigint NOT NULL REFERENCES warehouses(id),
    qty          integer NOT NULL DEFAULT 0,
    updated_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (variant_id, warehouse_id)
);

CREATE TABLE material_movements (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id   bigint NOT NULL REFERENCES materials(id),
    warehouse_id  bigint NOT NULL REFERENCES warehouses(id),
    moved_at      timestamptz NOT NULL,
    qty           numeric(14,3) NOT NULL CHECK (qty <> 0),
    movement_type varchar(20) NOT NULL CHECK (movement_type IN ('opening','purchase_in','production_out','adjustment','opname')),
    unit_cost     numeric(15,4),
    source_type   varchar(60), source_id bigint,
    note          varchar(255),
    created_by    bigint REFERENCES users(id),
    created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX mm_material_time_idx ON material_movements(material_id, moved_at);
CREATE INDEX mm_source_idx        ON material_movements(source_type, source_id);

CREATE TABLE material_balances (
    material_id  bigint NOT NULL REFERENCES materials(id),
    warehouse_id bigint NOT NULL REFERENCES warehouses(id),
    qty          numeric(14,3) NOT NULL DEFAULT 0,
    updated_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (material_id, warehouse_id)
);

CREATE OR REPLACE FUNCTION trg_stock_balance() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO stock_balances(variant_id, warehouse_id, qty, updated_at)
  VALUES (NEW.variant_id, NEW.warehouse_id, NEW.qty, now())
  ON CONFLICT (variant_id, warehouse_id)
  DO UPDATE SET qty = stock_balances.qty + EXCLUDED.qty, updated_at = now();
  RETURN NEW;
END $$;
CREATE TRIGGER stock_movements_balance AFTER INSERT ON stock_movements
  FOR EACH ROW EXECUTE FUNCTION trg_stock_balance();

CREATE OR REPLACE FUNCTION trg_material_balance() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO material_balances(material_id, warehouse_id, qty, updated_at)
  VALUES (NEW.material_id, NEW.warehouse_id, NEW.qty, now())
  ON CONFLICT (material_id, warehouse_id)
  DO UPDATE SET qty = material_balances.qty + EXCLUDED.qty, updated_at = now();
  RETURN NEW;
END $$;
CREATE TRIGGER material_movements_balance AFTER INSERT ON material_movements
  FOR EACH ROW EXECUTE FUNCTION trg_material_balance();

-- ledger tidak boleh diubah/dihapus (koreksi = baris baru)
CREATE OR REPLACE FUNCTION trg_ledger_readonly() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Ledger % tidak boleh diubah/dihapus, buat baris koreksi', TG_TABLE_NAME; END $$;
CREATE TRIGGER stock_movements_ro    BEFORE UPDATE OR DELETE ON stock_movements    FOR EACH ROW EXECUTE FUNCTION trg_ledger_readonly();
CREATE TRIGGER material_movements_ro BEFORE UPDATE OR DELETE ON material_movements FOR EACH ROW EXECUTE FUNCTION trg_ledger_readonly();

