    status          varchar(10) NOT NULL DEFAULT 'completed' CHECK (status IN ('pending','completed','returned','cancelled')),
    buyer_name      varchar(120),
    platform_fee    numeric(15,2),                    -- potongan admin AKTUAL dari export (NULL = pakai estimasi %)
    shipping_fee    numeric(15,2),
    import_batch_id bigint REFERENCES sales_import_batches(id),
    note            text,
    created_by      bigint REFERENCES users(id),
    created_at timestamptz, updated_at timestamptz,
    UNIQUE (store_id, order_no)
);
CREATE INDEX so_date_idx       ON sales_orders(order_date);
CREATE INDEX so_store_date_idx ON sales_orders(store_id, order_date);

CREATE TABLE sales_order_items (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sales_order_id         bigint NOT NULL REFERENCES sales_orders(id) ON DELETE CASCADE,
